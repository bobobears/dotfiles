#!/usr/bin/env python3
"""
检查今天是否是 A 股交易日。
返回 0 = 是交易日，1 = 非交易日（周末或节假日）。

做定时任务前置检查用，避免非交易日浪费 API 调用。

数据来源：上交所《关于上海证券交易所2026年部分节假日休市安排的通知》
（上证公告〔2025〕45号）+《关于2026年中秋节、国庆节休市安排的公告》
（上证公告〔2026〕22号）。已与 exchange_calendars XSHG 日历逐日核对一致。

注意：
1. 下面只列「工作日中的休市日」；周六周日恒为休市，无需列举。
2. 国务院调休的「周末补班日」（如 2026-09-20 周日、2026-10-10 周六）对
   证券交易所不适用——A股周末一律不开市，故不得计入交易日。
3. 每年 11-12 月国务院/交易所公布次年安排后，必须更新本表。
"""
import sys
from datetime import date

# 2026 年 A 股休市日（仅工作日，不含周末）
HOLIDAYS_2026 = {
    # 元旦 1/1(四)-1/3(六)
    "2026-01-01", "2026-01-02",
    # 春节 2/15(日)-2/23(一)
    "2026-02-16", "2026-02-17", "2026-02-18", "2026-02-19",
    "2026-02-20", "2026-02-23",
    # 清明节 4/4(六)-4/6(一)
    "2026-04-06",
    # 劳动节 5/1(五)-5/5(二)
    "2026-05-01", "2026-05-04", "2026-05-05",
    # 端午节 6/19(五)-6/21(日)
    "2026-06-19",
    # 中秋节 9/25(五)-9/27(日)
    "2026-09-25",
    # 国庆节 10/1(四)-10/7(三)
    "2026-10-01", "2026-10-02", "2026-10-05", "2026-10-06", "2026-10-07",
}

# 按年份组织的表，便于跨年
HOLIDAYS_BY_YEAR = {
    2026: HOLIDAYS_2026,
}


def is_trading_day(check_date=None):
    """判断是否A股交易日：周一至周五，扣除法定节假日"""
    if check_date is None:
        check_date = date.today()

    date_str = check_date.isoformat()
    weekday = check_date.weekday()  # 0=周一, 6=周日

    # 周末恒为休市（调休补班的周末同样不开市）
    if weekday >= 5:
        return False

    # 法定节假日
    if date_str in HOLIDAYS_BY_YEAR.get(check_date.year, set()):
        return False

    return True


if __name__ == "__main__":
    today = date.today()
    if is_trading_day(today):
        print(f"✅ {today} 是交易日")
        sys.exit(0)
    else:
        print(f"⏭️ {today} 非交易日，跳过")
        sys.exit(1)
